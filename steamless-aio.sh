#!/usr/bin/env bash
# ============================================================================
#   HUBCAP MANIFEST  //  steamless deck wrapper (all-in-one)
#   a steam server run by cats. brought to you by:
#     Hubcap  (boss)          Solus   (co-boss, only other boy)
#     Squegee (hubcap's sis)  Stella
#     Sadie                   Sage
#     Sophie                  Skylar
#   all the girls say meow. solus says meow too but lower.
#
#   single-file: steamless.py is embedded as base64 at the bottom.
#   just drop this script anywhere and run it - no extra files needed.
# ============================================================================
set -euo pipefail

PAYLOAD_SHA=4facf812b2ca343dd4c3e05324e1e0a2e557ec412635b1d0527385f9d13803cf

if [ -t 1 ]; then
    C_RESET=$'\033[0m'; C_BOLD=$'\033[1m'
    C_PINK=$'\033[38;5;213m'; C_CYAN=$'\033[38;5;87m'
    C_YELL=$'\033[38;5;227m'; C_GREEN=$'\033[38;5;120m'
    C_RED=$'\033[38;5;203m'; C_DIM=$'\033[2m'
else
    C_RESET=""; C_BOLD=""; C_PINK=""; C_CYAN=""; C_YELL=""; C_GREEN=""; C_RED=""; C_DIM=""
fi

meow() { echo "${C_PINK}[meow]${C_RESET} $*"; }
purr() { echo "${C_GREEN}[purr]${C_RESET} $*"; }
hiss() { echo "${C_RED}[hiss]${C_RESET} $*" >&2; }
yawn() { echo "${C_DIM}[...]  $*${C_RESET}"; }

banner() {
cat <<BANNER
${C_CYAN}${C_BOLD}
   _  _  _   _ ___  ___   _   ___   __  __   _   _  _ ___ ___ ___ ___ _____
  | || || | | | _ )/ __| /_\\ | _ \\ |  \\/  | /_\\ | \\| |_ _| __| __/ __|_   _|
  | __ || |_| | _ \\ (__ / _ \\|  _/ | |\\/| |/ _ \\| .\` || || _|| _|\\__ \\ | |
  |_||_| \\___/|___/\\___/_/ \\_\\_|   |_|  |_/_/ \\_\\_|\\_|___|___|___|___/ |_|
${C_RESET}${C_YELL}                      \\    /\\      steamstub unpacker
                       )  ( ')     deck edition (AIO)
                      (  /  )      ~ run by cats ~
                       \\(__)|
${C_RESET}
BANNER
}

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)"
VENV="$SCRIPT_DIR/.venv"
PY="${PYTHON:-python3}"
EMBEDDED_PY="$VENV/steamless.py"
EMBEDDED_SHA="$VENV/steamless.py.sha256"

banner

if ! command -v "$PY" >/dev/null 2>&1; then
    hiss "Sadie checked the shelf. no python3 in PATH. Hubcap is displeased."
    hiss ""
    hiss "Steam Deck fix:"
    hiss "  sudo steamos-readonly disable"
    hiss "  sudo pacman -S python python-pip"
    hiss "or use distrobox if you value your rootfs."
    exit 1
fi

if [ ! -x "$VENV/bin/python" ]; then
    meow "first run. summoning a venv in ${C_BOLD}$VENV${C_RESET}"
    meow "(Sage says this only happens once. go pet a cat.)"
    "$PY" -m venv "$VENV" || {
        hiss "venv creation failed. ensurepip may be blocked on your distro."
        hiss "try:  sudo pacman -S python-pip   (or your distro's equivalent)"
        exit 1
    }
    yawn "upgrading pip..."
    "$VENV/bin/python" -m pip install --quiet --upgrade pip
    yawn "installing pycryptodome (Sophie insists on crypto being present)..."
    "$VENV/bin/python" -m pip install --quiet pycryptodome
    yawn "installing capstone (Sadie needs it to read v2.x disassembly)..."
    "$VENV/bin/python" -m pip install --quiet capstone
    purr "venv ready. Stella approves."
fi

if ! "$VENV/bin/python" -c "import Crypto" 2>/dev/null; then
    meow "pycryptodome went missing (Squegee probably knocked it off the table)..."
    "$VENV/bin/python" -m pip install --quiet pycryptodome
    purr "put it back. Squegee denies everything."
fi
if ! "$VENV/bin/python" -c "import capstone" 2>/dev/null; then
    meow "capstone went missing (Sage suspects Sophie was involved)..."
    "$VENV/bin/python" -m pip install --quiet capstone
    purr "put it back. Sophie looks innocent."
fi

# ---- extract embedded steamless.py (only if missing or outdated) ----
NEED_EXTRACT=1
if [ -f "$EMBEDDED_PY" ] && [ -f "$EMBEDDED_SHA" ]; then
    if [ "$(cat "$EMBEDDED_SHA")" = "$PAYLOAD_SHA" ]; then
        NEED_EXTRACT=0
    fi
fi
if [ "$NEED_EXTRACT" -eq 1 ]; then
    yawn "extracting embedded steamless.py into venv..."
    awk '/^__PAYLOAD__$/{p=1; next} p' "$0" | base64 -d > "$EMBEDDED_PY"
    GOT_SHA="$(sha256sum "$EMBEDDED_PY" | awk '{print $1}')"
    if [ "$GOT_SHA" != "$PAYLOAD_SHA" ]; then
        hiss "payload hash mismatch. expected $PAYLOAD_SHA got $GOT_SHA"
        hiss "download may be corrupt. re-download the script."
        exit 1
    fi
    echo "$PAYLOAD_SHA" > "$EMBEDDED_SHA"
    purr "extracted. Hubcap signed off."
fi

# ---- dispatch ----
if [ $# -eq 0 ]; then
    meow "Skylar is napping. drop a game .exe path below (quotes/escaping optional),"
    meow "or Ctrl+C to bail."
    echo
    read -r -p "${C_YELL}path to exe:${C_RESET} " TARGET
    TARGET="${TARGET%\"}"; TARGET="${TARGET#\"}"
    TARGET="${TARGET%\'}"; TARGET="${TARGET#\'}"
    if [ -z "$TARGET" ]; then
        hiss "no path given. Skylar went back to sleep."
        exit 1
    fi
    if [ ! -f "$TARGET" ]; then
        hiss "file not found: $TARGET"
        exit 1
    fi
    purr "dispatching to steamless.py... Solus is supervising."
    purr "(in-place: original will be backed up to ${C_BOLD}<name>.original${C_RESET})"
    echo
    exec "$VENV/bin/python" "$EMBEDDED_PY" "$TARGET"
fi

purr "dispatching to steamless.py... Solus is supervising."
echo
exec "$VENV/bin/python" "$EMBEDDED_PY" "$@"

exit 0
